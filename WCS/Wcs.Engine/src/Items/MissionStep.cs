using System.ComponentModel;
using Wcs.Engine.Collections;
using Wcs.Common;

namespace Wcs.Engine.Items;

public class MissionStep
{
    #region Public Properties

    /// <summary>
    ///     Returns or sets the generation date of the step
    /// </summary>
    /// <returns></returns>
    [Browsable(true)]
    [Description("Returns or sets the generation date of the step")]
    [DisplayName("DateTime")]
    [Category("MissionStep")]
    public DateTime Date { get; set; }

    public AutomationDevice? DestinationItem
    {
        get
        {
            if (ToNodeId == null || ToNodeId == Guid.Empty) return null;
            return PathDevices.Instance[ToNodeId];
        }
        set
        {
            if (value == null)
                ToNodeId = null;
            else
                ToNodeId = value.ItemGuid;
        }
    }

    /// <summary>
    ///     Returns or sets the end of the step execution
    /// </summary>
    /// <returns></returns>
    [Browsable(true)]
    [Description("Returns or sets the end of the step execution")]
    [DisplayName("EndStep")]
    [Category("MissionStep")]
    public DateTime EndStep { get; set; }

    /// <summary>
    ///     Returns or sets the GroupRoutePathId to which a step belongs, this parameter allows you to track whether you have
    ///     already passed through a level in order to avoid repetitive search cycles
    /// </summary>
    /// <returns></returns>
    [Browsable(true)]
    [Description(
        "Returns or sets the GroupRoutePathId to which a step belongs, this parameter allows you to track whether you have already passed through a level in order to avoid repetitive search cycles")]
    [DisplayName("FromGroupRoutePath")]
    [Category("MissionStep")]
    public int FromGroupRoutePath { get; set; }

    /// <summary>
    ///     Returns or Sets the ItemGuid of the SourceId AutomationItem
    /// </summary>
    /// <returns></returns>
    [Browsable(true)]
    [Description("Returns or Sets the ItemGuid of the Source AutomationItem")]
    [DisplayName("FromNode")]
    [Category("MissionStep")]
    public Guid? FromNodeId { get; set; }

    /// <summary>
    ///     Returns or sets a series of steps generated by an AutomationItem of type GroupOfAutomationDevices
    /// </summary>
    /// <returns></returns>
    [Browsable(true)]
    [Description("Returns or sets a series of steps generated by an AutomationItem of type GroupOfAutomationDevices")]
    [DisplayName("GroupedMovementId")]
    [Category("MissionStep")]
    public Guid GroupedMovementId { get; set; } = Guid.Empty;

    /// <summary>
    ///     Returns or sets the identifier of the connected PathMission
    /// </summary>
    /// <returns></returns>
    [Browsable(true)]
    [Description("Returns or sets the identifier of the connected PathMission")]
    [DisplayName("MissionId")]
    [Category("MissionStep")]
    public Guid MissionId { get; set; }

    /// <summary>
    ///     Returns or sets the linked PathMission
    /// </summary>
    /// <returns></returns>
    [Browsable(true)]
    [Description("Returns or sets the linked PathMission")]
    [DisplayName("PathMission")]
    [Category("MissionStep")]
    public PathMission? PathMission
    {
        get
        {
            // Per chiave, non per scansione: era un FirstOrDefault su tutte le missioni attive, e
            // sta su un percorso caldo -- FindExecutedStep lo legge a ogni StepDone dal campo.
            // L'indicizzatore risponde in tempo costante e da' lo stesso risultato. Voce D80.
            return MissionId == Guid.Empty ? null : ActiveMissions.Instance[MissionId];
        }
        set => MissionId = value?.MissionId ?? Guid.Empty;
    }

    /// <summary>
    ///     Returns or sets the element that executes the step
    /// </summary>
    /// <returns></returns>
    [Browsable(true)]
    [Description("Returns or sets the element that executes the step")]
    [DisplayName("RunningItem")]
    [Category("MissionStep")]
    public AutomationDevice? RunningItem
    {
        get
        {
            if (RunningNode == null || RunningNode == Guid.Empty) return null;
            return PathDevices.Instance[RunningNode];
        }
        set
        {
            if (value == null)
                RunningNode = null;
            else
                RunningNode = value.ItemGuid;
        }
    }

    /// <summary>
    ///     Returns or sets the ItemGuid of the item that executes the step
    /// </summary>
    /// <returns></returns>
    [Browsable(true)]
    [Description("Returns or sets the ItemGuid of the item that executes the step")]
    [DisplayName("RunningNode")]
    [Category("MissionStep")]
    public Guid? RunningNode { get; set; }

    /// <summary>
    ///     Returns or sets the source element
    /// </summary>
    /// <returns></returns>
    [Browsable(true)]
    [Description("Returns or sets the source element")]
    [DisplayName("SourceItem")]
    [Category("MissionStep")]
    public AutomationDevice? SourceItem
    {
        get
        {
            if (FromNodeId == null || FromNodeId == Guid.Empty) return null;
            return PathDevices.Instance[FromNodeId];
        }
        set
        {
            if (value == null)
                FromNodeId = null;
            else
                FromNodeId = value.ItemGuid;
        }
    }

    /// <summary>
    ///     Returns or sets the start of the step execution
    /// </summary>
    /// <returns></returns>
    [Browsable(true)]
    [Description("Returns or sets the start of the step execution")]
    [DisplayName("StartStep")]
    [Category("MissionStep")]
    public DateTime StartStep { get; set; }

    /// <summary>
    ///     Returns or sets the unique id of the step
    /// </summary>
    /// <returns></returns>
    [Browsable(true)]
    [Description("Returns or sets the unique id of the step")]
    [DisplayName("StepId")]
    [Category("MissionStep")]
    public Guid StepId { get; set; }

    /// <summary>
    ///     Returns or sets the execution status of the step
    /// </summary>
    /// <returns></returns>
    [Browsable(true)]
    [Description("Returns or sets the execution status of the step")]
    [DisplayName("StepStatus")]
    [Category("MissionStep")]
    public Enums.ResultCodeTypes StepStatus { get; set; }

    /// <summary>
    ///     Returns or sets the ItemGuid of the DestinationId AutomationDeviceBase
    /// </summary>
    /// <returns></returns>
    [Browsable(true)]
    [Description("Returns or sets the ItemGuid of the Destination AutomationDevice")]
    [DisplayName("ToNode")]
    [Category("MissionStep")]
    public Guid? ToNodeId { get; set; }

    #endregion Public Properties

    #region Public Methods

    public void Remove()
    {
        MissionSteps.Instance.Remove(this);
    }

    #endregion Public Methods
}